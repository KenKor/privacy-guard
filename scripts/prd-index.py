#!/usr/bin/env python3
"""Regenerate the "Overview by state" block in `docs/prds/index.md`.

A PRD's **folder is its status**; progress is the checkboxes in its own plan; the name is the
filename. The one field that cannot be derived is the one-line hook, so it lives in the PRD as a
`**Hook:**` paragraph and travels with it when it moves.

    scripts/prd-index.py            # report drift; exit 1 if the block is stale
    scripts/prd-index.py --write    # regenerate it

On a merge conflict inside the markers, do not hand-merge: take either side and run `--write`.
Adjust PRD_DIR and FOLDERS below per repo; list deviations in the repo's docs/agents/.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRD_DIR = os.path.join(ROOT, "docs", "prds")
INDEX = os.path.join(PRD_DIR, "index.md")
BEGIN = "<!-- prd-index:begin: generated by scripts/prd-index.py; do not edit by hand -->"
END = "<!-- prd-index:end -->"

FOLDERS = [
    ("new", "untriaged intake"),
    ("triaged", "triaged, tracked as an issue"),
    ("research", "spike in progress"),
    ("designed", "written, decisions open"),
    ("reviewed", "decisions closed, ready to slice into tickets"),
    ("implemented", "all tickets closed, suite green, review and docs pending"),
    ("blocked", "parked by necessity"),
    ("deferred", "parked by choice"),
    ("completed", "shipped and documented"),
    ("rejected", "investigated and dropped"),
]
COUNTED = {"new", "triaged", "research", "designed", "reviewed", "implemented", "blocked", "deferred"}

HOOK_RE = re.compile(r"^\*\*Hook:\*\*[ \t]*(.*)$", re.M)
HOOK_STOP_RE = re.compile(r"^\s*(?:$|\*\*[^*\n]+:\*\*|#{1,6}(?:\s|$)|```|\||[-*] |\d+\. |>(?:\s|$)|<!--)")
BOX_RE = re.compile(r"^- \[( |x)\]", re.M)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def hook_text(text):
    m = HOOK_RE.search(text)
    if not m:
        return ""
    parts = [m.group(1).strip()]
    for line in text[m.end():].split("\n")[1:]:
        if HOOK_STOP_RE.match(line):
            break
        parts.append(line.strip())
    return " ".join(p for p in parts if p)


def progress(text):
    boxes = BOX_RE.findall(text)
    return f"{boxes.count('x')}/{len(boxes)}" if boxes else ""


def render():
    known = {f for f, _ in FOLDERS}
    extra = sorted(
        d for d in os.listdir(PRD_DIR) if os.path.isdir(os.path.join(PRD_DIR, d)) and d not in known
    )
    lines = []
    for folder, gloss in FOLDERS + [(d, "(folder not in FOLDERS)") for d in extra]:
        d = os.path.join(PRD_DIR, folder)
        files = sorted(f for f in os.listdir(d) if f.endswith(".md")) if os.path.isdir(d) else []
        lines.append(f"### {folder}/ ({len(files)}): {gloss}")
        lines.append("")
        for f in files:
            text = read(os.path.join(d, f))
            bits = [f"[{f}]({folder}/{f})"]
            if folder in COUNTED and progress(text):
                bits.append(f"`{progress(text)}`")
            hook = hook_text(text)
            line = "- " + " ".join(bits) + (f": {hook}" if hook else "")
            lines.append(line)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    block = f"{BEGIN}\n\n{render()}\n{END}"
    current = read(INDEX) if os.path.exists(INDEX) else f"# PRD index\n\n{BEGIN}\n{END}\n"
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(current):
        sys.exit(f"{INDEX}: markers not found")
    new = pat.sub(lambda _: block, current)
    if "--write" in sys.argv:
        with open(INDEX, "w", encoding="utf-8") as f:
            f.write(new)
        print("index written")
        return 0
    if new != current:
        print("PRD index is stale; run scripts/prd-index.py --write")
        return 1
    print("PRD index is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
